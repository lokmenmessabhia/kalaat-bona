class UIManager {
    constructor() {
        this.theme = localStorage.getItem('theme') || 'light';
        this.lang = localStorage.getItem('lang') || 'fr';
        this.init();
    }

    init() {
        this.applyTheme(this.theme);
        this.applyLanguage(this.lang);
        this.bindEvents();
    }

    t(key) {
        if (translations[this.lang] && translations[this.lang][key]) {
            return translations[this.lang][key];
        }
        return key;
    }

    applyTheme(theme) {
        this.theme = theme;
        localStorage.setItem('theme', theme);

        const body = document.body;
        if (theme === 'dark') {
            body.classList.add('dark');
        } else {
            body.classList.remove('dark');
        }

        // Update all theme icons
        const iconIds = ['themeIcon', 'mobileThemeIcon'];
        iconIds.forEach(id => {
            const icon = document.getElementById(id);
            if (icon) {
                icon.className = theme === 'dark' ? 'fa-solid fa-sun' : 'fa-solid fa-moon';
            }
        });

        // Update toggle button titles
        const toggleBtn = document.getElementById('themeToggle');
        if (toggleBtn) toggleBtn.setAttribute('title', theme === 'dark' ? this.t('theme_toggle_light') : this.t('theme_toggle_dark'));
        const mobileToggleBtn = document.getElementById('mobileThemeToggle');
        if (mobileToggleBtn) mobileToggleBtn.querySelector('span').textContent = theme === 'dark' ? this.t('theme_toggle_light') : this.t('theme_toggle_title');
    }

    toggleTheme() {
        this.applyTheme(this.theme === 'light' ? 'dark' : 'light');
    }

    setLanguage(lang) {
        this.applyLanguage(lang);
    }

    applyLanguage(lang) {
        this.lang = lang;
        localStorage.setItem('lang', lang);

        document.documentElement.setAttribute('lang', lang);
        document.body.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

        // Update label
        const label = document.getElementById('currentLangLabel');
        if (label) {
            const map = { fr: 'FR', en: 'EN', ar: 'AR' };
            label.textContent = map[lang] || 'FR';
        }

        // Update mobile lang buttons
        document.querySelectorAll('.mobile-lang-btn').forEach(btn => {
            btn.classList.toggle('active', btn.dataset.lang === lang);
        });

        // Translate elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                el.textContent = translations[lang][key];
            }
        });

        // Translate placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (translations[lang] && translations[lang][key]) {
                el.placeholder = translations[lang][key];
            }
        });

        // Dispatch event for dynamic content (e.g. programme cards)
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    }

    bindEvents() {
        // Desktop theme toggle
        const themeBtn = document.getElementById('themeToggle');
        if (themeBtn) themeBtn.addEventListener('click', () => this.toggleTheme());

        // Mobile theme toggle
        const mobileThemeBtn = document.getElementById('mobileThemeToggle');
        if (mobileThemeBtn) mobileThemeBtn.addEventListener('click', () => this.toggleTheme());

        // Language dropdown toggle
        const langToggle = document.getElementById('langToggle');
        const langDropdown = document.getElementById('langDropdown');
        if (langToggle && langDropdown) {
            langToggle.addEventListener('click', (e) => {
                e.stopPropagation();
                langDropdown.classList.toggle('show');
            });
            document.addEventListener('click', () => langDropdown.classList.remove('show'));
        }

        // Language options (desktop)
        document.querySelectorAll('.lang-option').forEach(btn => {
            btn.addEventListener('click', (e) => {
                e.preventDefault();
                this.setLanguage(btn.dataset.lang);
                document.getElementById('langDropdown')?.classList.remove('show');
            });
        });

        // Language options (mobile)
        document.querySelectorAll('.mobile-lang-btn').forEach(btn => {
            btn.addEventListener('click', () => {
                this.setLanguage(btn.dataset.lang);
            });
        });
    }
}

const uiManager = new UIManager();
